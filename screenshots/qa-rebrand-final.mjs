import { chromium } from "playwright";
const BASE = "http://127.0.0.1:8080";
const OUT = "/workspace/screenshots";
const browser = await chromium.launch({ args: ["--disable-dev-shm-usage"] });
const ctx = await browser.newContext({ viewport: { width: 1280, height: 800 } });
const page = await ctx.newPage();
await page.addInitScript(() => {
  sessionStorage.setItem("rabotaem-splash", "1");
  localStorage.setItem("rabotaem-lang", "ro");
  localStorage.setItem("rabotaem-theme", "light");
});
await page.goto(BASE, { waitUntil: "networkidle", timeout: 30000 });
await page.waitForTimeout(400);
const body = await page.locator("body").innerText();
console.log("JobPeLoc in body?", /JobPeLoc/i.test(body));
console.log("title", await page.title());
await page.screenshot({ path: `${OUT}/rebrand-home-light.png` });
await page.evaluate(() => window.scrollTo(0, document.body.scrollHeight));
await page.waitForTimeout(200);
await page.screenshot({ path: `${OUT}/rebrand-footer-light.png` });
await browser.close();
console.log("done");
