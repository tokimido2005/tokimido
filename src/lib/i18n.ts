const loading: Partial<Record<Locale, Promise<void>>> = {};

/** Make sure a language's strings are loaded (RO is always bundled). */
export function loadLocale(locale: Locale): Promise<void> {
  if (locale === "ro" || Object.keys(messages[locale]).length > 0) return Promise.resolve();
  loading[locale] ??= loaders[locale]()
    .then((mod) => {
      messages[locale] = mod.default;
    })
    .catch((err) => {
      loading[locale] = undefined;
      throw err;
    });
  return loading[locale]!;
}

let roRare: Record<string, string> = {};
let roRarePromise: Promise<void> | null = null;

/**
 * Load the Romanian texts that only the privacy page and Admin use (kept out
 * of the main download). Safe to call many times.
 */
export function loadRareRomanian(): Promise<void> {
  roRarePromise ??= import("./i18n-locales/ro-rare").then((m) => {
    roRare = m.default;
  });
  return roRarePromise;
}

export function translate(locale: Locale, key: string, vars?: Record<string, string | number>) {
  let text = messages[locale]?.[key] ?? messages.ro[key] ?? roRare[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      text = text.replaceAll(`{${k}}`, String(v));
    }
  }
  return text;
}

