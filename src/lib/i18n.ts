/** Human text for a server error, in the visitor's language. */
export function errorText(
  err: unknown,
  t: (key: string, vars?: Record<string, string | number>) => string,
  fallback: string,
) {
  const message = (err instanceof Error ? err.message : typeof err === "string" ? err : "").trim();
  if (!message) return fallback;
  const rate = /^rate\.limit\|(\d+)$/.exec(message);
  if (rate) return t("error.rateLimit", { m: rate[1] });
  const smsErr = /^(sms\.err\w+)(?:\|(\d+))?$/.exec(message);
  if (smsErr) return t(smsErr[1], smsErr[2] ? { n: smsErr[2] } : undefined);
  const known = SERVER_ERROR_KEYS[message];
  if (known) return t(known);
  const banned = /^Contul este blocat: (.+)$/s.exec(message);
  if (banned) return t("srv.bannedReason", { r: banned[1] });
  // Coded keys thrown by newer server code (account.*, srv.*, error.*).
  if (/^(account|srv|error|tg|cv|company)\.[A-Za-z0-9_.]+$/.test(message)) return t(message);
  // Raw schema-validation output (JSON issue list) is not for humans.
  if (message.startsWith("[") && message.includes('"code"')) {
    // Validation issues may carry a translation key as their message.
    try {
      const issues = JSON.parse(message) as Array<{ message?: string }>;
      const coded = issues.find((i) => i.message && /^[a-z]+\.[A-Za-z0-9_.]+$/.test(i.message));
      if (coded?.message) {
        const text = t(coded.message);
        if (text !== coded.message) return text;
      }
    } catch {
      /* fall through */
    }
    return t("error.invalidInput");
  }
  return message;
}

